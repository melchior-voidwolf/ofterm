import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1280, height: 820 } })
await page.goto('http://127.0.0.1:5122/?nogl=1', { waitUntil: 'networkidle' })
await page.waitForTimeout(900)
await page.getByRole('button', { name: '设置' }).click()
await page.getByRole('tab', { name: 'Help' }).click()
await page.getByRole('button', { name: '在当前终端安装辅助工具' }).click()
await page.waitForTimeout(500)
console.log('toast immediate', await page.locator('.toast').count())
await page.waitForTimeout(3500)
console.log('toast after 4s', await page.locator('.toast').count())
await browser.close()
